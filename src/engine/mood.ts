const PATTERNS = [
  'לחץ', 'לחוץ', 'לחוצה', 'חרדה', 'חרד', 'מפחד', 'פוחד', 'פחד', 'נמאס', 'מתוסכל', 'תסכול', 'מייאש', 'ייאוש',
  'לא מצליח', 'אין לי סיכוי', 'אני גרוע', 'אני דפוק', 'די כבר', 'שונא את זה', 'אני טיפש', 'לא אצליח', 'נכשל', 'קשה לי',
]

export function detectDistress(text: string): boolean {
  const t = text.replace(/\s+/g, ' ').trim()
  if (!t) return false
  return PATTERNS.some((p) => t.includes(p))
}

