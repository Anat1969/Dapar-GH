function numberOptions(right, spread = 3) {
  const set = new Set([right])
  const opts = [right]
  let guard = 0
  while (opts.length < 4 && guard++ < 50) {
    const d = right + int(-spread, spread)
    if (d >= 0 && !set.has(d)) { set.add(d); opts.push(d) }
  }
  return opts.map(String)
}

