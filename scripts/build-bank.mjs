import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'

const uuid = (key) => {
  const h = createHash('sha1').update('dapar:' + key).digest('hex')
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`
}

let seed = 20261029
const rnd = () => {
  seed |= 0
  seed = (seed + 0x6d2b79f5) | 0
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}
const pick = (arr) => arr[Math.floor(rnd() * arr.length)]
const int = (a, b) => a + Math.floor(rnd() * (b - a + 1))

/** מערבב אפשרויות ומחזיר את מיקום התשובה הנכונה. התשובה הנכונה היא הראשונה ברשימה שנמסרת. */
function shuffle(options) {
  const idx = options.map((_, i) => i)
  for (let i = idx.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1))
    ;[idx[i], idx[j]] = [idx[j], idx[i]]
  }
  return { options: idx.map((i) => options[i]), correct_index: idx.indexOf(0) }
}

/** באפשרויות מספריות: מחליף כפילויות ומספרים שליליים במספרים קרובים שלא בשימוש. */
function fixNumeric(opts) {
  if (!opts.every((o) => typeof o === 'string' && /^-?\d+(\.\d+)?$/.test(o))) return opts
  const right = Number(opts[0])
  const used = new Set([opts[0]])
  const step = Number.isInteger(right) ? 1 : 0.5
  return opts.map((o, i) => {
    if (i === 0) return o
    let v = Number(o)
    let k = 1
    while (used.has(String(v)) || v < 0) { v = right + (k % 2 ? 1 : -1) * Math.ceil(k / 2) * step * 2; k++ }
    used.add(String(v))
    return String(v)
  })
}

const bank = []
const keys = new Set()
function add(key, q) {
  if (keys.has(key)) throw new Error('duplicate ' + key)
  keys.add(key)
  q.options = fixNumeric(q.options)
  const { options, correct_index } = shuffle(q.options)
  const uniq = new Set(options.map((o) => JSON.stringify(o)))
  if (uniq.size !== options.length) throw new Error('duplicate options in ' + key + ' ' + JSON.stringify(options))
  bank.push({
    id: uuid(key),
    domain: q.domain,
    layer: q.layer,
    skill: q.skill,
    difficulty: q.difficulty ?? 1,
    prompt: q.prompt,
    instruction_text: q.instruction_text ?? null,
    figure: q.figure ?? null,
    options,
    correct_index,
    explanation: q.explanation,
    source: 'new',
    time_limit_seconds: q.time ?? (q.layer === 'application' ? 60 : null),
  })
}

